def _fill(tpl: str, slots: Dict[str, str]) -> str:
    return re.sub(r"\{([^{}]*)\}", lambda m: slots.get(m.group(1), ""), tpl)


def _endp(s: str) -> str:
    s = s.strip()
    if not s:
        return s
    return s if s[-1] in TERMINAL or ord(s[-1]) > 0x2FFF and not s[-1].isalnum() else s + "。"


def _fit(P: Dict[str, Any], F: Dict[str, Any]) -> float:
    f, n = F["fit"], P["名"]
    s = 1.0
    if n == "数据官":
        s += (1.5 if f["stat"] else 0) + (0.8 if f["goals"] else 0) + (0.4 if f["form"] else 0)
    elif n == "盘口老炮":
        s += (1.5 if f["line"] else 0) + (0.5 if "北单" in F["plays"] else 0)
    elif n == "毒舌解说":
        s += (0.8 if f["rec"] else 0.3) + (0.8 if f["support"] else 0) + (0.4 if f["risk"] else 0)
    elif n == "热血球迷":
        s += (0.8 if f["night"] else 0.2) + (0.6 if f["plays"] >= 2 else 0) + (0.4 if f["rec"] else 0)
    elif n == "冷门猎手":
        s += (2.5 if f["risk"] else 0.2)
    elif n == "佛系老哥":
        s += (1.2 if not f["rec"] else 0.3) + (0.6 if not f["stat"] else 0) + (0.5 if f["night"] else 0)
    elif n == "段子手":
        s += (0.8 if not f["rec"] else 0.4) + (0.6 if f["night"] else 0)
    elif n == "战术教授":
        s += (1.5 if f["form"] else 0) + (0.8 if f["goals"] else 0)
    return s


def _pool(P: Dict[str, Any], kind: str, F: Dict[str, Any]) -> List[Tuple[int, str]]:
    """这个人设、这个类别里，这场比赛能用的句子（用到的位置词当天都有数据）。"""
    fl, avail = F["flags"], F["slots"]
    if kind == "支持" and not fl["support"]:
        return []
    if kind == "存疑" and not fl["mixed"]:
        return []
    if kind == "防平" and not fl["draw"]:
        return []
    if kind == "分歧" and not fl["div"]:
        return []
    if kind == "防冷" and not fl["cold"]:
        return []
    if not F["rec"] and kind in ("推荐", "数据"):
        return []
    return [(i, t) for i, t in enumerate(P.get(kind, [])) if all(n in avail for n in _slots_of(t))]


def _resolve(tok: str, F: Dict[str, Any], P: Dict[str, Any], rng: random.Random) -> Optional[str]:
    """结构里的一个名字 → 这场实际用的类别（没有可用句子就是 None）。"""
    alts = tok.split("|")
    kinds: List[str] = []
    for a in alts:
        if a == "核对":
            kinds.append("支持" if F["flags"]["support"] else "存疑" if F["flags"]["mixed"] else "")
        elif a == "风险":
            kinds += [k for k, on in (("防平", F["flags"]["draw"]), ("分歧", F["flags"]["div"]), ("防冷", F["flags"]["cold"])) if on]
        elif a == "推荐":
            kinds.append("推荐" if F["rec"] else "观战")
        else:
            kinds.append(a)
    ok = [k for k in dict.fromkeys(kinds) if k and _pool(P, k, F)]
    return rng.choice(ok) if ok else None


def _names_match(tpl: str) -> bool:
    """这句话里是不是已经把「哪两队」说全了。"""
    s = set(_slots_of(tpl))
    return "对阵" in s or {"主", "客"} <= s or {"推荐队", "对手"} <= s


_DROP_ORDER = ("收尾", "支持", "存疑", "防平", "分歧", "防冷", "盘口", "数据", "近况", "开场")


def _build_line(F: Dict[str, Any], P: Dict[str, Any], rng: random.Random, used: set, max_len: int, bad: Sequence[str], emoji: bool) -> Optional[Tuple[str, List[Tuple[str, int]]]]:
    """一次只说一个观点或事实；避免模板串联，超长时换整句而不截断。"""
    limit = min(max_len, 48)  # 旧设置110字也会使用短句上限；不改写用户设置文件。
    slots = dict(F["slots"])
    if str(slots.get("方向", "")).endswith("胜"):
        slots["方向"] = slots["方向"][:-1] + "赢"
    slots["对阵"] = f"{F['home']}对{F['away']}"
    bank = P.get("简短评论", SHORT_LINES)
    flags = F.get("flags", {})
    kinds = ["观战"]
    if F.get("rec"):
        kinds += ["推荐", "近况", "盘口"]
    for kind, flag in (("防平", "draw"), ("分歧", "div"), ("防冷", "cold")):
        if F.get("rec") and flags.get(flag):
            kinds.append(kind)
    candidates = []
    kind_counts = Counter(entry[2] for entry in used if len(entry) == 4 and entry[:2] == ("同场类别", F["key"]))
    for kind in kinds:
        if kind == "推荐" and kind_counts[kind] >= 2:
            continue
        if kind == "盘口" and not slots.get("盘口"):
            continue
        pool = bank.get(kind, [])
        indexed = list(enumerate(pool))
        if len(indexed) > 80:
            indexed = rng.sample(indexed, 80)
        previous = [entry[2] for entry in used if len(entry) == 3 and entry[:2] == ("同场短句", F["key"])]
        for i, template in indexed:
            family = SHORT_FAMILIES.get(template, "自定义:" + template)
            if ("同场句意", F["key"], family) in used:
                continue
            if not all(key in slots for key in _slots_of(template)):
                continue
            text = " ".join(_fill(template, slots).split()).strip()
            if not 6 <= len(text) <= limit or has_bad(text, bad) or "{" in text or "}" in text:
                continue
            if F["home"] not in text and F["away"] not in text:
                if "方向" in _slots_of(template):
                    text = f"{F['home']}对{F['away']}，" + text
                if len(text) > limit or (F["home"] not in text and F["away"] not in text):
                    continue
            if ("短句文本", text.rstrip("。！？!?")) in used:
                continue
            # 同场已用过的近似说法不换几个字再出一条。
            if any(SequenceMatcher(None, text, old).ratio() > 0.84 for old in previous):
                continue
            priority = 1.0 - kind_counts[kind] * 1.5
            if ("批内句意", family) in used:
                priority -= 3.0
            if kind == "推荐":
                priority += 0.8
            if kind == "近况" and P["名"] == "数据官":
                priority += 1.2
            if kind in ("防平", "防冷") and P["名"] == "冷门猎手":
                priority += 1.0
            if kind == "观战" and F.get("rec"):
                priority -= 0.4
            if ("简短句式", kind, i) in used:
                priority -= 2.0
            candidates.append((priority + rng.random() * 2, kind, i, text))
    if not candidates:
        return None
    _, kind, i, text = max(candidates)
    if text.endswith("。") and rng.random() < 0.3:
        text = text[:-1]
    family = SHORT_FAMILIES.get(bank[kind][i], "自定义:" + bank[kind][i])
    used.add(("同场句意", F["key"], family))
    used.add(("批内句意", family))
    used.add(("同场类别", F["key"], kind, i))
    used.add(("简短句式", kind, i))
    used.add(("短句文本", text.rstrip("。！？!?")))
    used.add(("同场短句", F["key"], text))
    return text, [(kind, i)]


def _seed(*xs: Any) -> int:
    return zlib.crc32("|".join(str(x) for x in xs).encode("utf-8"))


def compose(data: Dict[str, Any], lib: Dict[str, Any], *, seed: int = 0, per: int = 6, watch_per: int = 3, max_len: int = 42, recap_n: int = 5,
            ask_n: int = 4, bad: Sequence[str] = (), emoji: bool = True, only: Sequence[str] = ()) -> Dict[str, Any]:
    """生成话术。同一份数据、同一个种子，结果一模一样。only：只用这几个人设（空 = 全部启用的人设）。"""
    day = data.get("day", "")
    personas = [p for p in lib["人设"] if p.get("启用", True) and (not only or p["名"] in only)]
    used: set = set()
    lead = Counter()
    items: List[Dict[str, Any]] = []
    for F in data["matches"]:
        n = min(per if F["rec"] else watch_per, len(personas))
        lines: List[Dict[str, str]] = []
        if n > 0:
            rng = random.Random(_seed(day, F["key"], seed, "pick"))
            scored = sorted(personas, key=lambda P: -(_fit(P, F) + rng.random() * 0.9 - 0.05 * lead[P["名"]]))
            for P in scored[:n]:
                r2 = random.Random(_seed(day, F["key"], P["名"], seed))
                got = _build_line(F, P, r2, used, max_len, bad, emoji)
                if not got:
                    continue
                text, marks = got
                for k, i in marks:
                    used.add((P["名"], k, i))
                lead[P["名"]] += 1
                lines.append({"persona": P["名"], "icon": P.get("表情", ""), "text": text})
        items.append({"key": F["key"], "home": F["home"], "away": F["away"], "lg": F["lg"], "kick": F["kick"], "no": F["no"], "rec": F["rec"],
                      "dir": F["slots"].get("方向", ""), "time": F["slots"].get("时间", ""), "lines": lines})
    summ = data.get("summary") or {}
    rng = random.Random(_seed(day, seed, "summary"))
    sl = [t for t in lib.get("今日总评", []) if all(n in summ for n in _slots_of(t))]
    rng.shuffle(sl)
    intro = [_endp(_fill(t, summ)) for t in sl[:3]]
    al = [t for t in lib.get("互动提问", []) if all(n in summ for n in _slots_of(t))]
    random.Random(_seed(day, seed, "ask")).shuffle(al)
    asks = [_endp(_fill(t, summ)) for t in al[:max(0, ask_n)]]
    recap_lines: List[Dict[str, str]] = []
    rc = list(data.get("recap") or [])
    if rc and recap_n > 0 and personas:
        r3 = random.Random(_seed(day, seed, "recap"))
        hits = [r for r in rc if r["hit"]]
        miss = [r for r in rc if not r["hit"]]
        r3.shuffle(hits)
        r3.shuffle(miss)
        order: List[Dict[str, Any]] = []
        while (hits or miss) and len(order) < recap_n:
            if miss:
                order.append(miss.pop())
            if hits and len(order) < recap_n:
                order.append(hits.pop())
        plist = personas[:]
        r3.shuffle(plist)
        for j, r in enumerate(order):
            kind = "赛后命中" if r["hit"] else "赛后未中"
            slots = {"主": r["home"], "客": r["away"], "对阵": f"{r['home']}对{r['away']}", "方向": r["dir"], "结果": r["score"]}
            for k in range(len(plist)):
                P = plist[(j + k) % len(plist)]
                c = [t for t in lib.get("简短评论", SHORT_LINES).get(kind, []) if all(n in slots for n in _slots_of(t))]
                if not c:
                    continue
                text = _endp(_fill(r3.choice(c), slots))
                if len(text) <= min(max_len, 48) and not has_bad(text, bad):
                    recap_lines.append({"persona": P["名"], "icon": P.get("表情", ""), "text": text, "hit": "1" if r["hit"] else "0"})
                    break
    nh = sum(1 for r in rc if r["hit"])
    out: Dict[str, Any] = {"day": day, "seed": seed, "intro": intro, "items": items, "recap": recap_lines, "recap_sum": (nh, len(rc) - nh) if rc else None,
                           "asks": asks, "personas": [p["名"] for p in personas]}
    out["variant_count"] = sum(len(lines) for lines in lib.get("简短评论", SHORT_LINES).values())
    out["n_match"] = len(items)
    out["n_line"] = sum(len(i["lines"]) for i in items)
    out["text"] = render_text(out)
    out["plain"] = render_plain(out)
    out["n_line"] = len(out["plain"].splitlines())
    return out


def render_text(out: Dict[str, Any]) -> str:
    """默认导出纯评论：一行一条，不附标题、标签或说明。"""
    return render_plain(out)


def render_plain(out: Dict[str, Any]) -> str:
    """每条评论独占一行，去重并去掉条目内部的换行。"""
    lines: List[str] = []
    seen: set = set()
    records = [ln for it in out.get("items", []) for ln in it.get("lines", [])]
    records += list(out.get("recap", []))
    for record in records:
        line = " ".join(str(record.get("text", "")).split()).strip()
        if line and line not in seen:
            seen.add(line)
            lines.append(line)
    return "\n".join(lines) + ("\n" if lines else "")


def persona_names(lib: Dict[str, Any]) -> List[str]:
    return [p["名"] for p in lib["人设"] if p.get("启用", True)]


