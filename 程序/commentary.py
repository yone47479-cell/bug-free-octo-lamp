def ensure_lib_file(path: Path) -> List[str]:
    """首次创建话术库；旧文件补缺，保留完整旧默认分类时无损扩充新短句。返回做了什么（空 = 什么都没做）。"""
    done: List[str] = []
    try:
        if not path.exists():
            _atomic_write(path, json.dumps(lib_default_json(), ensure_ascii=False, indent=2))
            return ["新建话术库"]
        data = json.loads(path.read_text(encoding="utf-8-sig"))
        if isinstance(data, dict):
            upgraded = []
            short = data.get("简短评论")
            if isinstance(short, dict):
                for kind, base in BASE_SHORT_LINES.items():
                    values = short.get(kind)
                    if isinstance(values, list) and set(base).issubset(v for v in values if isinstance(v, str)):
                        merged_lines = list(dict.fromkeys(v for v in values + SHORT_LINES[kind] if isinstance(v, str)))
                        if values != merged_lines:
                            short[kind] = merged_lines
                            upgraded.append(kind)
            miss = [k for k in DEFAULT_LIB if k not in data]
            if miss or "各项说明" not in data or upgraded:
                dflt = lib_default_json()
                merged = {k: (data[k] if k in data else dflt[k]) for k in dflt}
                merged["各项说明"] = dflt["各项说明"]
                if upgraded:
                    merged["话术库版本"] = LIB_VERSION
                merged.update({k: v for k, v in data.items() if k not in merged})
                _atomic_write(path, json.dumps(merged, ensure_ascii=False, indent=2))
                done = [f"补上 {k}" for k in miss] + (["扩充随机短评句库"] if upgraded else [])
    except (OSError, ValueError):
        pass
    return done


def _slots_of(tpl: str) -> List[str]:
    return re.findall(r"\{([^{}]*)\}", tpl)


def has_bad(text: str, bad: Sequence[str]) -> bool:
    """含违禁词（前面有「不」「没有」等否定的不算）。"""
    for w in bad:
        for m in re.finditer(re.escape(w), text):
            pre = text[max(0, m.start() - 4):m.start()]
            if not any(n in pre for n in NEGATIONS):
                return True
    return False


def _tpl_ok(t: Any, bad: Sequence[str], allow: Sequence[str]) -> Optional[str]:
    """一句模板是否可用。可用返回 None，否则返回原因。"""
    if not isinstance(t, str) or not t.strip():
        return "不是文字"
    if len(t) > 90:
        return "太长（超过 90 字）"
    names = _slots_of(t)
    for n in names:
        if n not in allow:
            return f"用了不认识的位置词「{{{n}}}」"
    if "{" in re.sub(r"\{[^{}]*\}", "", t) or "}" in re.sub(r"\{[^{}]*\}", "", t):
        return "大括号不成对"
    if has_bad(t, bad):
        return "含违禁词"
    return None


def _struct_ok(s: Any) -> Optional[List[List[str]]]:
    if not isinstance(s, list) or not s:
        return None
    out: List[List[str]] = []
    for row in s:
        if not isinstance(row, list) or not row or any(not isinstance(x, str) for x in row):
            return None
        for tok in row:
            for alt in tok.rstrip("?").split("|"):
                if alt not in STRUCT_TOKENS:
                    return None
        out.append([x.strip() for x in row])
    return out


def _norm_persona(e: Any, bad: Sequence[str], warns: List[str]) -> Optional[Dict[str, Any]]:
    if not isinstance(e, dict) or not isinstance(e.get("名"), str) or not e["名"].strip():
        warns.append(f"话术库「人设」里有一项没有「名」，已跳过：{str(e)[:30]}")
        return None
    name = e["名"].strip()
    on = e.get("启用", True)
    if not isinstance(on, bool):
        warns.append(f"人设「{name}」的「启用」应是 true 或 false，已当作 true")
        on = True
    icon = e.get("表情", "")
    if not isinstance(icon, str):
        icon = ""
    p: Dict[str, Any] = {"名": name, "表情": icon.strip()[:4], "启用": on, "简介": str(e.get("简介", "")) if isinstance(e.get("简介", ""), str) else ""}
    st = _struct_ok(e["结构"]) if "结构" in e else None
    if "结构" in e and st is None:
        warns.append(f"人设「{name}」的「结构」写得不对（应是 [[\"开场?\", \"推荐\"], …]，名字只能用：{'、'.join(sorted(STRUCT_TOKENS))}），已用默认拼法")
    p["结构"] = st or copy.deepcopy(DEFAULT_STRUCT)
    for k in KINDS:
        raw = e.get(k, [])
        if isinstance(raw, str):
            raw = [raw]
        if not isinstance(raw, list):
            warns.append(f"人设「{name}」的「{k}」应是一个句子列表，已跳过这一类")
            raw = []
        keep: List[str] = []
        dropped: List[Tuple[str, str]] = []
        allow = SLOT_NAMES
        for t in raw:
            why = _tpl_ok(t, bad, allow)
            if why:
                dropped.append((str(t)[:24], why))
            else:
                keep.append(t.strip())
        if dropped:
            warns.append(f"人设「{name}」的「{k}」里有 {len(dropped)} 句不能用（{dropped[0][1]}：{dropped[0][0]}…），已跳过")
        p[k] = keep
    if not p["推荐"] and not p["观战"]:
        warns.append(f"人设「{name}」没有可用的「推荐」或「观战」句子，已跳过这个人设")
        return None
    return p


def load_lib(path: Optional[Path], bad: Sequence[str] = ()) -> Tuple[Dict[str, Any], List[str]]:
    """读句库。没有文件/某项写得不对 → 那一项用默认值。返回（句库, 提醒）。句库里写了违禁词的句子会被丢掉。"""
    warns: List[str] = []
    default, _ = _build_lib(copy.deepcopy(DEFAULT_LIB), bad, [])
    if path is None or not Path(path).exists():
        return default, warns
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        return default, [f"话术库 {LIB_FILE} 读不了（{exc}），这次用默认句库。删掉它会自动重建。"]
    if not isinstance(data, dict):
        return default, [f"话术库 {LIB_FILE} 格式不对（最外层应是 {{ }}），这次用默认句库。"]
    known = set(DEFAULT_LIB) | {"各项说明"}
    for k in data:
        if k not in known:
            warns.append(f"话术库里的「{k}」不认识，已忽略（是不是写错了字？）")
    lib, w2 = _build_lib(data, bad, warns)
    return lib, w2


def _build_lib(data: Dict[str, Any], bad: Sequence[str], warns: List[str]) -> Tuple[Dict[str, Any], List[str]]:
    lib: Dict[str, Any] = {"话术库版本": LIB_VERSION}
    ps = data.get("人设", DEFAULT_LIB["人设"])
    out: List[Dict[str, Any]] = []
    if isinstance(ps, list):
        for e in ps:
            p = _norm_persona(e, bad, warns)
            if p:
                out.append(p)
        names = [p["名"] for p in out]
        for n in {x for x in names if names.count(x) > 1}:
            warns.append(f"话术库里有两个人设都叫「{n}」，只用第一个")
        seen: set = set()
        out = [p for p in out if not (p["名"] in seen or seen.add(p["名"]))]
    else:
        warns.append("话术库「人设」应是一个列表，已用默认句库")
        out = []
    if not out:
        if isinstance(ps, list):
            warns.append("话术库里没有一个能用的人设，这次用默认句库")
        d: List[Dict[str, Any]] = []
        for e in DEFAULT_LIB["人设"]:
            p = _norm_persona(e, bad, [])
            if p:
                d.append(p)
        out = d
    raw_short = data.get("简短评论", SHORT_LINES)
    if not isinstance(raw_short, dict):
        warns.append("简短评论应为分类句库，已使用默认短句")
        raw_short = SHORT_LINES
    short = {}
    for kind, defaults in SHORT_LINES.items():
        values = raw_short.get(kind, defaults)
        values = [values] if isinstance(values, str) else values
        if not isinstance(values, list):
            values = defaults
        if set(BASE_SHORT_LINES.get(kind, ())).issubset(v for v in values if isinstance(v, str)):
            values = list(values) + list(defaults)
        keep = [t.strip() for t in values if _tpl_ok(t, bad, SLOT_NAMES) is None]
        short[kind] = list(dict.fromkeys(keep))
    lib["简短评论"] = short
    for persona in out:
        persona["简短评论"] = short
    lib["人设"] = out
    for key, allow in (("今日总评", ("日期", "总场数", "推荐场数", "最早", "最晚", "主打联赛", "联赛数")),
                       ("互动提问", ("日期", "总场数", "推荐场数", "最早", "最晚", "主打联赛", "联赛数"))):
        raw = data.get(key, DEFAULT_LIB[key])
        if isinstance(raw, str):
            raw = [raw]
        keep: List[str] = []
        if not isinstance(raw, list):
            warns.append(f"话术库「{key}」应是一个句子列表，已用默认值")
            raw = DEFAULT_LIB[key]
        bad_n = 0
        for t in raw:
            if _tpl_ok(t, bad, allow) is None:
                keep.append(t.strip())
            else:
                bad_n += 1
        if bad_n:
            warns.append(f"话术库「{key}」里有 {bad_n} 句不能用（位置词不认识、太长或含违禁词），已跳过")
        lib[key] = keep
    return lib, warns


